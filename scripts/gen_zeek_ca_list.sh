# Converts a PEM CA bundle into a zeek mozilla-ca-list.zeek (redef SSL::root_certs).
# usage: gen_zeek_ca_list.sh [bundle] [stock zeek list to diff against] > mozilla-ca-list.zeek
# Certs with an already seen subject are skipped, and the subjects of the stock list that are
# missing from the output are reported on stderr.

set -e

BUNDLE=${1:-/etc/ssl/certs/ca-certificates.crt}
STOCK=${2:-/usr/local/zeek/share/zeek/base/protocols/ssl/mozilla-ca-list.zeek}

TMP_DIR=$(mktemp -d)
trap 'rm -rf "$TMP_DIR"' EXIT

awk -v dir="$TMP_DIR" '
  /-----BEGIN CERTIFICATE-----/ { n++; out = sprintf("%s/%04d.pem", dir, n) }
  out { print > out }
  /-----END CERTIFICATE-----/ { close(out); out = "" }
' "$BUNDLE"

echo "# Don't edit!  This file is automatically generated by scripts/gen_zeek_ca_list.sh."
VERSION=$(dpkg-query -W -f='${Version}' ca-certificates 2>/dev/null) || VERSION=""
echo "# Generated from: $BUNDLE${VERSION:+ (ca-certificates $VERSION)}"
echo
echo "@load base/protocols/ssl"
echo "module SSL;"
echo "redef root_certs += {"

touch "$TMP_DIR/subjects"
for pem in "$TMP_DIR"/*.pem; do
  # zeek names a cert by its RFC2253 subject, the same form as the stock list
  subject=$(openssl x509 -in "$pem" -noout -subject -nameopt RFC2253 | sed 's/^subject=//')
  # zeek keys root_certs by subject, so keep the first cert like upstream gen-mozilla-ca-list.py
  if grep -qxF -- "$subject" "$TMP_DIR/subjects"; then
    echo "skipping duplicate subject in $BUNDLE: $subject" >&2
    continue
  fi
  echo "$subject" >> "$TMP_DIR/subjects"
  der=$(openssl x509 -in "$pem" -outform DER | od -An -v -tx1 | tr -d ' \n' | tr 'a-f' 'A-F' | sed 's/../\\x&/g')
  printf '\t["%s"] = "%s",\n' "$subject" "$der"
done

echo "};"

count=$(wc -l < "$TMP_DIR/subjects")
echo "generated $count root certs" >&2
if [[ -f "$STOCK" ]]; then
  sed -n 's/^\t\["\(.*\)"\] = ".*$/\1/p' "$STOCK" | sort > "$TMP_DIR/stock"
  sort "$TMP_DIR/subjects" > "$TMP_DIR/new"
  echo "roots in $STOCK but not in the output:" >&2
  comm -23 "$TMP_DIR/stock" "$TMP_DIR/new" >&2
fi
